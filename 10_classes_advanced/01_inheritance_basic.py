# 상속하는 이유 (상속 하면 할 수 있는 것)
# 1. 부모 메서드 교체 (오버라이딩)
# 2. 새로운 메서드 추가

# 부모 클래스
class Bicycle:
    def pedal(self):
        print('자전거 페달을 밟는다')

    def gear(self):
        print('자전거 기어를 조정한다.')

# 자식 클래스 (인자로 부모 클래스 들어가야 함)
class AutoBicycle(Bicycle):
    def pedal(self):    # 오버라이딩 (메서드 재 정의)
        print('승차감이 좋아유')

    def auto(self):     # 메서드 추가
        print('자동 주행이에욥')

    def bike(self):
        super().gear()  # 부모 클래스의 메서드 호출 할 수 있음
        print('그리고, 1단부터 5단까지 조절할 수 있어요')

# 인스턴스 생성
cycle = AutoBicycle()

# 메서드 호출
cycle.pedal()
cycle.auto()
cycle.gear()
cycle.bike()
