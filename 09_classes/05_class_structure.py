# =============================================================
# 클래스의 구조 - 클래스 변수 vs 인스턴스 변수
# - 클래스 변수  : 모든 인스턴스가 '공유'하는 값 (설계도에 적힌 값)
# - 인스턴스 변수 : 인스턴스마다 '따로' 갖는 값 (붕어빵마다 다른 속)
# =============================================================

# -----------------------------------------
# 추가 매모
# 

class Circle:
    # 클래스 변수: 클래스 안, 메서드 밖에 직접 정의
    # => 모든 Circle 인스턴스가 공유 (원주율은 어떤 원이든 같으므로)
    pi = 3.14

    # 생성자 메서드(인스턴스 생성 시 자동 호출되는 특별한 메서드 / 인스턴스 변수의 초가화 담당)
    def __init__(self, radius):
        # 인스턴스 변수: self.을 붙여 정의(인스턴스마다 독립적인 값 유지)
        # => 원마다 반지름이 다르므로 인스턴스별로 따로 저장
        self.radius = radius


# 인스턴스 생성
c1 = Circle(1)
c2 = Circle(2)

# =============================================================
# 인스턴스 변수(radius) - 인스턴스마다 값이 다름
# =============================================================

# 인스턴스 변수(속성) 접근
print(None)  # 1
print(None)  # 2

# =============================================================
# 클래스 변수(pi) - 모든 인스턴스가 같은 값을 공유
# - c1.pi, c2.pi 모두 클래스에 있는 하나의 pi를 바라봄
# =============================================================

# 클래스 변수(공통 속성) 접근
print(None)  # 3.14
print(None)  # 3.14
