# Q) 저글링 클래스 만들기
# - 필드(속성) (생성자에서 구형)
#   - hp =20
#   - mana =50
# - run() 메서드
#     - 뛴다 라는 Text 출력
#     - hp 가 1 줄어든다
#     - mana 가 1 올라간다.
# - show_status() 메서드
#     - hp 와 mana 를 출력한다.
# ** 앞에서 제작한 저글링 클래스 사용하는 코드 만들기
# - 저글링 두마리를 만든다.
#     - 변수 z1, z2 에 생성
# - 저글링을 각각 동작시킨다.
#     - z1 은 run 이후 show_status 호출
#     - z2 는 run 5회 이후 show_status 호출

class ju:
    def __init__(self):
        self.hp = 20
        self.mana = 50

    def run(self):
        print("뛴다")
        self.hp -= 1
        self.mana += 1

    def show_status(self):
        print(f'hp: {self.hp}, mana: {self.mana}')

z1 = ju()
z2 = ju()

z1.run()
z1.show_status()

for i in range(5):
    z2.run()
z2.show_status()

