# 클래스(Class) - 객체를 만들어내는 '설계도' ( 관련된 데이터(속성)와 기능(메서드)을 하나의 '묶음'으로 정의하는 설계도 )
# - 붕어빵 틀에 비유: 클래스가 틀이라면, 실제 붕어빵이 인스턴스
# - 클래스 = 자동차 설계도 / 속성 = 자동차의 데이터(색상, 최고속도, 좌석 수, 배기량 등 / 메서드 = 자동차 기능 / 인스턴스 = 실제 자동차)
# - class 키워드로 정의하며, 클래스 이름은 첫 글자를 대문자로 (관례) => 파스칼 케이스 /(_ 쓰는건 스네이크 케이스 => 함수에서 사용)
# =============================================================


class Person:
    # =========================================================
    # 생성자 __init__ - 인스턴스가 만들어질 때 자동으로 실행됨
    # - self : 앞으로 만들어질 인스턴스 자기 자신을 가리킴
    #          (호출 시 자동으로 전달되므로 직접 넘기지 않음)
    # - self.name = name : 전달받은 값을 '이 인스턴스의 속성'으로 저장
    #   => self.을 붙여야 인스턴스에 남고, 안 붙이면 함수 안에서 사라짐
    # =========================================================
    def __init__(self, name, age):
        self.name = name  # 인스턴스 속성
        self.age = age  # 인스턴스 속성

    # =========================================================
    # 인스턴스 메서드 - 이 클래스로 만든 객체가 할 수 있는 동작
    # - 첫 번째 매개변수는 항상 self
    # - self.name 처럼, 저장해 둔 자기 속성을 꺼내 쓸 수 있음
    # =========================================================
    def introduce(self):
        print(f'안녕하세요. 저는 {self.name}, 나이는 {self.age}살입니다.')

