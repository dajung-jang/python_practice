# 메서드 : 클래스 내부에 정의된 함수 / 해당 객체가 어떻게 동작할지 정의

# =============================================================
# 인스턴스 메서드 (Instance Method) : 인스턴스의 상태를 조작하거나 동작을 수행
# - 인스턴스가 자기 데이터를 다루는 메서드 (첫 인자가 self) // 반드시 첫 번째 인자로 인스턴스 자신(self) 을 받음
# - self를 통해 '호출한 바로 그 인스턴스'의 변수에 접근/수정
# =============================================================

class Counter:
    # 생성자 : 객체가 만들어질 때 자동 호출되어 초기 상태 설정
    # self == 앞으로 만들어질 인스턴스 자기 자신
    def __init__(self):
        self.count = 0  # 인스턴스마다 따로 갖는 카운트

    # 인스턴스 메서드
    # 첫 번째 매개변수 self 는 호출 시 자동으로 전달 됨
    def increment(self):
        # 이 메서드를 호출하는 인스턴스의 변수 count를 1 증가 시키는 메서드
        # self.count => 'increment를 호출한 그 인스턴스'의 count
        self.count += 1


# =============================================================
# c1과 c2는 서로 다른 count를 가짐 (인스턴스는 독립적)
# - c1.increment()는 c1의 count만 1로 만듦
# - c2는 아무 것도 하지 않았으므로 여전히 0
#   => c1.increment()가 사실은 Counter.increment(c1)로 동작하기 때문
#      (self 자리에 c1이 자동으로 들어감)
# =============================================================

c1 = Counter()
c2 = Counter()
# 인스턴스 메서드 호출
print(c1.count)  # 0
c1.increment()
print(c1.count)  # 1
print(c2.count)  # 0

